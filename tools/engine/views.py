#!/usr/bin/env python3
"""Emit managed/Framework/Engine/Views.g.cs: one typed view per engine class, from EngineLayout's rows.

A view is a pointer-sized struct over the engine object, so reading a pointer field AS a view is the same
load as reading it as an IntPtr. A row typed `Field<T>` gets `ref T Name`; a `vtbl.*` row gets
`IntPtr NameFn`, the slot's code address; an untyped row gets nothing -- typing it is the port.

    tools/engine/views.py      # build.sh runs it; the output is checked in for the Windows builds
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'managed/Framework/EngineLayout.cs'
OUT = ROOT / 'managed/Framework/Engine/Views.g.cs'
DECL = re.compile(r'public static readonly int (\w+) =\s*Field(?:<([^>]+)>)?\(\s*"([^"]+)",\s*"([^"]+)"')
VIEW = 'CX.Engine.'


def ident(s):
    return re.sub(r'\W', '_', s)


def prop(field):
    return field[0].upper() + field[1:]


def main():
    classes = {}
    for row, typ, cls, field in DECL.findall(SRC.read_text()):
        if cls.startswith('('):                 # (abi): a layout of the C++ runtime, not an engine class
            continue
        if field.startswith('vtbl.'):
            member = (f'{prop(field[5:])}Fn',
                      f'public IntPtr {prop(field[5:])}Fn => *(IntPtr*)(*(IntPtr*)Ptr + EngineLayout.{row});')
        elif typ:
            t = typ.removeprefix(VIEW)
            member = (prop(field), f'public ref {t} {prop(field)} => ref *({t}*)(Ptr + EngineLayout.{row});')
            if typ.startswith(VIEW):
                classes.setdefault(t, {})
        else:
            continue
        name, line = member
        members = classes.setdefault(ident(cls), {})
        if name in members or name in ('Ptr', 'IsNull', ident(cls)):
            sys.exit(f'!! {cls}.{field}: view member {name} collides; rename the field in the build files')
        members[name] = f'    /// <inheritdoc cref="EngineLayout.{row}"/>\n    {line}'

    out = ['// <auto-generated> by tools/engine/views.py from EngineLayout.cs -- do not edit. </auto-generated>',
           'using System;', 'using CX.Framework;', '', 'namespace CX.Engine;', '']
    for cls in sorted(classes):
        out += [f'/// <summary>Typed view of an engine <c>{cls}*</c>.</summary>',
                f'public readonly unsafe struct {cls}(IntPtr ptr)', '{',
                '    /// <summary>The engine object.</summary>',
                '    public readonly IntPtr Ptr = ptr;',
                '    /// <summary>No object.</summary>',
                '    public bool IsNull => Ptr == IntPtr.Zero;']
        out += [classes[cls][m] for m in sorted(classes[cls])]
        out += ['}', '']
    text = '\n'.join(out)
    if not OUT.exists() or OUT.read_text() != text:
        OUT.parent.mkdir(exist_ok=True)
        OUT.write_text(text)
        print(f'>> wrote {OUT.relative_to(ROOT)} ({len(classes)} views)')


if __name__ == '__main__':
    main()
